// =============================================
// INICIALIZACIÓN 
// =============================================
document.addEventListener("DOMContentLoaded", function () {

  // Guard: verificar que el selector de idioma existe en esta página
  const selector = document.getElementById("language")
  if (!selector) return

  // Evento cambio de idioma
  selector.addEventListener("change", function () {
    setLanguage(this.value)
  })

  // Cargar idioma guardado o español por defecto
  const savedLang = localStorage.getItem("language") || "es"
  selector.value = savedLang
  setLanguage(savedLang)

})


// =============================================
// FUNCIÓN PRINCIPAL DE TRADUCCIÓN
// =============================================
function setLanguage(lang) {

  // 1. Actualizar atributo lang del documento (WCAG)
  document.documentElement.lang = lang

  // 2. Traducir todos los elementos con data-i18n
  document.querySelectorAll("[data-i18n]").forEach(function (element) {
    const key = element.getAttribute("data-i18n")

    // Fallback: si falta la clave en el idioma activo, usar español
    const text =
      (translations[lang] && translations[lang][key]) ||
      (translations["es"] && translations["es"][key]) ||
      key  

    element.textContent = text
  })

  // 3. Guardar preferencia del usuario
  localStorage.setItem("language", lang)

  // 4. Anunciar cambio para lectores de pantalla
  announceLanguageChange(lang)
}


// =============================================
// ANUNCIO ACCESIBLE 
// =============================================
function announceLanguageChange(lang) {
  const message = lang === "es"
    ? "Idioma cambiado a español"
    : "Language changed to English"

  const liveRegion = document.getElementById("language-status")
  if (!liveRegion) return

  
  liveRegion.textContent = ""
  setTimeout(function () {
    liveRegion.textContent = message
  }, 50)
}